from __future__ import annotations

import csv
import hashlib
import io
import random
from pathlib import Path

from PIL import Image

from .dataset import EXTRA_COLUMNS, MANIFEST_COLUMNS

SYNTHETIC_ID = "opera-synthetic-v1"
# (lat, lon, country, continent). Coordinates are arbitrary stand-ins: the images are generated noise
# blocks that depict nothing, so no model can legitimately locate them. They test the harness only.
_POINTS = [
    (48.86, 2.35, "FR", "Europe"),
    (35.68, 139.65, "JP", "Asia"),
    (-33.87, 151.21, "AU", "Oceania"),
    (40.71, -74.01, "US", "North America"),
    (-1.29, 36.82, "KE", "Africa"),
    (-34.60, -58.38, "AR", "South America"),
    (59.91, 10.75, "NO", "Europe"),
    (28.61, 77.21, "IN", "Asia"),
]


def _image_bytes(index: int) -> bytes:
    rng = random.Random(index * 7919 + 13)
    tiny = Image.new("RGB", (8, 8))
    tiny.putdata([tuple(rng.randrange(256) for _ in range(3)) for _ in range(64)])
    big = tiny.resize((128, 96), Image.NEAREST)
    out = io.BytesIO()
    big.save(out, format="PNG")
    return out.getvalue()


def write_synthetic_dataset(benchmark_dir: Path, dataset_id: str = SYNTHETIC_ID) -> Path:
    """Deterministic: the same call always writes byte-identical files. Four seed and four heldout images."""
    root = Path(benchmark_dir) / dataset_id
    (root / "images").mkdir(parents=True, exist_ok=True)
    rows = []
    for index, (lat, lon, country, continent) in enumerate(_POINTS):
        data = _image_bytes(index)
        filename = f"syn{index:02d}.png"
        (root / "images" / filename).write_bytes(data)
        rows.append(
            {
                "image_id": f"syn{index:02d}",
                "source_url": "",
                "license": "CC0-1.0 (generated by OPERA)",
                "author": "OPERA synthetic generator",
                "lat": lat,
                "lon": lon,
                "country": country,
                "settlement_type": "synthetic",
                "landscape": "synthetic",
                "image_source_type": "synthetic",
                "split": "seed" if index % 2 == 0 else "heldout",
                "continent": continent,
                "filename": filename,
                "image_url": "",
                "sha256": hashlib.sha256(data).hexdigest(),
            }
        )
    with (root / "manifest.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=[*MANIFEST_COLUMNS, *EXTRA_COLUMNS], lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return root
